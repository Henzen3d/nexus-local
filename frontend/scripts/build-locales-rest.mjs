import fs from 'fs'
import path from 'path'

const dir = path.resolve('src/i18n/locales')
const enUS = JSON.parse(fs.readFileSync(path.join(dir, '_base-en.json'), 'utf8'))
const clone = (o) => JSON.parse(JSON.stringify(o))

function applyOverrides(base, map) {
  const out = clone(base)
  for (const [pathKey, value] of Object.entries(map)) {
    const parts = pathKey.split('.')
    let cur = out
    for (let i = 0; i < parts.length - 1; i++) {
      if (!(parts[i] in cur)) cur[parts[i]] = {}
      cur = cur[parts[i]]
    }
    cur[parts[parts.length - 1]] = value
  }
  return out
}

function writeLocale(code, obj) {
  fs.writeFileSync(path.join(dir, `${code}.json`), JSON.stringify(obj, null, 2) + '\n', 'utf8')
  console.log('wrote', code)
}

